"use client";

import { useState, useMemo, useId } from "react";
import { Download, Upload, X } from "lucide-react";
import { cn } from "@/lib/utils";
import { useApp } from "@/lib/app-context";
import { validateParam } from "@/lib/param-engine";
import { buttonClass } from "@/components/ui/styles";
import type { Param } from "@/lib/types";

interface SaveConfirmModalProps {
  protectedParams: Param[];
  remainingParams: Param[];
  remainingOverrides: Map<string, string>;
  fileName: string | null;
  onConfirm: (header: string | null) => void;
  onPublishToCatalog?: (header: string | null) => void;
  onClose: () => void;
}

function StatRow({
  value,
  label,
  colorClass,
}: {
  value: number;
  label: string;
  colorClass: string;
}) {
  return (
    <div className="flex items-center justify-between gap-4 py-2">
      <span className="text-sm text-foreground">{label}</span>
      <span className={cn("shrink-0 font-mono text-lg font-semibold tabular-nums", colorClass)}>
        {value}
      </span>
    </div>
  );
}

export function SaveResumeModal({
  protectedParams,
  remainingParams,
  remainingOverrides,
  fileName,
  onConfirm,
  onPublishToCatalog,
  onClose,
}: SaveConfirmModalProps) {
  const { paramDefs, acknowledgedInvalid, activeListName } = useApp();
  const [includeHeader, setIncludeHeader] = useState(true);
  const titleId = useId();
  const headerId = useId();

  const invalidCount = useMemo(() => {
    let count = 0;
    for (const p of remainingParams) {
      if (acknowledgedInvalid.has(p.name)) continue;
      const def = paramDefs[p.name];
      if (!def) continue;
      const effectiveValue = remainingOverrides.get(p.name) ?? p.value;
      if (validateParam(effectiveValue, def) !== null) count++;
    }
    return count;
  }, [remainingParams, remainingOverrides, paramDefs, acknowledgedInvalid]);

  const acknowledgedCount = useMemo(
    () => remainingParams.filter((p) => acknowledgedInvalid.has(p.name)).length,
    [remainingParams, acknowledgedInvalid]
  );

  const modifiedCount = remainingOverrides.size;

  const buildHeader = (): string => {
    const date = new Date().toISOString().slice(0, 10);
    const invalids: string[] = [];
    const acknowledged: string[] = [];
    for (const p of remainingParams) {
      const def = paramDefs[p.name];
      if (!def) continue;
      const effectiveValue = remainingOverrides.get(p.name) ?? p.value;
      const reason = validateParam(effectiveValue, def);
      if (!reason) continue;
      const entry = `${p.name}=${effectiveValue} (${reason})`;
      if (acknowledgedInvalid.has(p.name)) acknowledged.push(entry);
      else invalids.push(entry);
    }
    return [
      "# Generated by AIR6 Param Filter",
      `# Date: ${date}`,
      fileName ? `# Source: ${fileName}` : null,
      `# Filter: ${activeListName}`,
      `# Applied: ${remainingParams.length} params | Protected (removed): ${protectedParams.length} params`,
      invalids.length > 0 ? `# Invalid values: ${invalids.join(", ")}` : null,
      acknowledged.length > 0 ? `# Acknowledged (user-reviewed): ${acknowledged.join(", ")}` : null,
      "#",
    ].filter(Boolean).join("\n") + "\n";
  };

  const handleDownload = () => {
    onConfirm(includeHeader ? buildHeader() : null);
    onClose();
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-4">
      <div className="absolute inset-0 bg-slate-950/50 backdrop-blur-xs" onClick={onClose} />

      <div
        role="dialog"
        aria-modal="true"
        aria-labelledby={titleId}
        className="relative z-10 flex max-h-[90vh] w-full max-w-md flex-col overflow-hidden rounded-2xl border border-border bg-card shadow-2xl"
      >
        {/* Header */}
        <div className="flex shrink-0 items-center justify-between gap-3 border-b border-border px-5 py-3.5">
          <h2 id={titleId} className="text-base font-semibold text-foreground">Save Filtered File</h2>
          <button
            type="button"
            onClick={onClose}
            className={buttonClass("ghost", "icon", "-mr-1.5")}
            aria-label="Close"
            title="Close"
          >
            <X className="h-4 w-4" />
          </button>
        </div>

        <div className="flex min-h-0 flex-1 flex-col overflow-y-auto px-5 py-2">
          {/* Stats */}
          <div className="flex flex-col divide-y divide-border">
            <StatRow
              value={protectedParams.length}
              label="params filtered out (protected)"
              colorClass="text-protected-text"
            />
            <StatRow
              value={remainingParams.length}
              label="params will be written"
              colorClass="text-applied-text"
            />
            {invalidCount > 0 && (
              <StatRow
                value={invalidCount}
                label="invalid values"
                colorClass="text-red-700 dark:text-red-400"
              />
            )}
            {acknowledgedCount > 0 && (
              <StatRow
                value={acknowledgedCount}
                label="acknowledged by user"
                colorClass="text-blue-700 dark:text-blue-400"
              />
            )}
            {modifiedCount > 0 && (
              <StatRow
                value={modifiedCount}
                label="value overrides"
                colorClass="text-amber-700 dark:text-amber-400"
              />
            )}
          </div>

          {/* Metadata toggle */}
          <div className="flex items-center gap-2.5 border-t border-border py-3">
            <input
              id={headerId}
              type="checkbox"
              checked={includeHeader}
              onChange={(e) => setIncludeHeader(e.target.checked)}
            />
            <label htmlFor={headerId} className="cursor-pointer select-none text-sm text-foreground">
              Include metadata header
            </label>
          </div>
        </div>

        {/* Footer */}
        <div className="flex shrink-0 flex-wrap items-center justify-end gap-2 border-t border-border bg-secondary/40 px-5 py-3">
          <button
            type="button"
            onClick={onClose}
            className={buttonClass("secondary")}
          >
            Cancel
          </button>
          {onPublishToCatalog && (
            <button
              type="button"
              onClick={() => { onPublishToCatalog(includeHeader ? buildHeader() : null); onClose(); }}
              className={buttonClass("secondary")}
            >
              <Upload className="h-3.5 w-3.5" />
              Save to a drone…
            </button>
          )}
          <button
            type="button"
            onClick={handleDownload}
            className={buttonClass("primary")}
          >
            <Download className="h-3.5 w-3.5" />
            Download
          </button>
        </div>
      </div>
    </div>
  );
}
